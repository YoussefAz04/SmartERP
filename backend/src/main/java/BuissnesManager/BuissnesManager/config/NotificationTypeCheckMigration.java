package BuissnesManager.BuissnesManager.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.CommandLineRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * One-time migration that drops any existing CHECK constraint on the
 * {@code notification.type} column and recreates it with all current
 * {@link BuissnesManager.BuissnesManager.entity.NotificationType} values.
 *
 * <p>SQL Server auto-generates a CHECK constraint when Hibernate creates the
 * column via {@code ddl-auto=update}. If new enum values are added later the
 * constraint still only permits the original values, causing INSERT failures
 * such as {@code CK__notificati__type__370627FE}.</p>
 *
 * <p>The migration is idempotent: on subsequent runs it drops and recreates
 * the constraint with the same set of values, which is a harmless no-op in
 * practice.</p>
 */
@Component
@Order(4)
public class NotificationTypeCheckMigration implements CommandLineRunner {

    private static final Logger logger = LoggerFactory.getLogger(NotificationTypeCheckMigration.class);

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Override
    public void run(String... args) {
        dropExistingCheckConstraints();
        createUpdatedCheckConstraint();
    }

    /**
     * Drops every CHECK constraint that targets the {@code type} column on the
     * {@code notification} table.  The constraint name is auto-generated by
     * SQL Server so we look it up dynamically via {@code sys.check_constraints}.
     */
    private void dropExistingCheckConstraints() {
        try {
            var constraints = jdbcTemplate.queryForList(
                "SELECT cc.name " +
                "FROM sys.check_constraints cc " +
                "JOIN sys.columns c ON cc.parent_object_id = c.object_id " +
                "      AND cc.parent_column_id = c.column_id " +
                "WHERE cc.parent_object_id = OBJECT_ID('notification') " +
                "  AND c.name = 'type'"
            );

            for (var row : constraints) {
                String constraintName = (String) row.get("name");
                if (constraintName != null && isSafeIdentifier(constraintName)) {
                    jdbcTemplate.execute(
                        "ALTER TABLE [notification] DROP CONSTRAINT [" + constraintName + "]"
                    );
                    logger.info("NotificationTypeCheckMigration: dropped CHECK constraint '{}'", constraintName);
                }
            }
        } catch (Exception e) {
            logger.warn("NotificationTypeCheckMigration: could not drop existing CHECK constraint(s) - {}", e.getMessage());
        }
    }

    /**
     * Creates a CHECK constraint that permits all current
     * {@code NotificationType} enum values.
     */
    private void createUpdatedCheckConstraint() {
        try {
            jdbcTemplate.execute(
                "ALTER TABLE [notification] WITH NOCHECK ADD CONSTRAINT [CHK_notification_type] " +
                "CHECK ([type] IN ('RUPTURE','FAIBLE_STOCK','ALERTE_COMMANDE','STOCK_REPRISE','ARTICLE_AJOUTE','STOCK_AJOUTE'))"
            );
            logger.info("NotificationTypeCheckMigration: created CHECK constraint CHK_notification_type with all current enum values");
        } catch (Exception e) {
            logger.warn("NotificationTypeCheckMigration: could not create CHECK constraint - {}", e.getMessage());
        }
    }

    private static boolean isSafeIdentifier(String identifier) {
        return identifier != null && identifier.matches("[A-Za-z_][A-Za-z0-9_]*");
    }
}
